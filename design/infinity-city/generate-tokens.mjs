/**
 * Regenerates `design/infinity-city/tokens.json` from the single source of truth
 * in `packages/common/infinity/src/factions.ts`.
 *
 * Usage (Node >= 22.6):
 *   node --experimental-strip-types design/infinity-city/generate-tokens.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../packages/common/infinity/src/factions.ts');

const { FACTIONS, FACTION_ORDER, DEFAULT_FACTION } = await import(source);

const tokens = {
  $schema: '../../packages/common/infinity/src/factions.ts',
  version: '2.0.0',
  project: 'Prometheus Project: Infinity',
  layer: 'Skill Intelligence Layer',
  package: '@afk/theme-infinity',
  defaultFaction: DEFAULT_FACTION,
  order: FACTION_ORDER,
  cssVarPrefix: '--infinity-',
  factions: Object.fromEntries(
    FACTION_ORDER.map(code => {
      const faction = FACTIONS[code];
      return [
        code,
        {
          code: faction.code,
          name: faction.name,
          role: faction.role,
          concept: faction.concept,
          feeling: faction.feeling,
          claim: faction.claim,
          difference: faction.difference,
          accent: faction.accent,
          accentInk: faction.accentInk,
          background: faction.background,
          palette: Object.fromEntries(
            faction.colors.map((color, index) => [
              `color${index + 1}`,
              { hex: color.hex, role: color.role },
            ])
          ),
          typography: faction.typography,
          geometry: faction.geometry,
          atmosphere: faction.atmosphere,
          effects: faction.effects,
          ui: faction.ui,
          ...(faction.symbol ? { symbol: faction.symbol } : {}),
        },
      ];
    })
  ),
};

const target = resolve(here, 'tokens.json');
writeFileSync(target, `${JSON.stringify(tokens, null, 2)}\n`);

/**
 * The showcase page is plain HTML/JS, so it cannot import TypeScript.
 * Emit the faction data as a browser global instead of keeping a copy.
 */
const factionsJs = `/* eslint-disable */
/* AUTO-GENERATED by design/infinity-city/generate-tokens.mjs — do not edit.
 * Source of truth: packages/common/infinity/src/factions.ts
 */
window.FACTIONS = ${JSON.stringify(
  Object.fromEntries(
    FACTION_ORDER.map(code => {
      const {
        code: factionCode,
        accent,
        name,
        concept,
        role,
        feeling,
        claim,
        difference,
        background,
        colors,
        effects,
        ui,
        atmosphere,
        symbol,
      } = FACTIONS[code];
      return [
        factionCode,
        {
          code: factionCode,
          accent,
          name,
          concept,
          role,
          feeling,
          claim,
          difference,
          background,
          colors,
          effects,
          ui,
          atmosphere,
          ...(symbol ? { symbol } : {}),
        },
      ];
    })
  ),
  null,
  2
)};
window.FACTION_ORDER = ${JSON.stringify(FACTION_ORDER)};
`;
writeFileSync(resolve(here, 'factions.js'), factionsJs);
console.log(
  `generated: tokens.json + factions.js (${FACTION_ORDER.length} factions)`
);
